// Generates src/agent-mode.generated.css from src/styles.css: for every solid
// border, the same rule under html.agent-mode with that side dashed. Only the
// sides a rule sets are touched, so no new borders appear. Run it after
// changing borders in styles.css (npm run build does it for you).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = postcss.parse(readFileSync(`${root}src/styles.css`, 'utf8'));
const out = postcss.root();

const SIDES = {
  border: ['border-style'],
  'border-top': ['border-top-style'],
  'border-right': ['border-right-style'],
  'border-bottom': ['border-bottom-style'],
  'border-left': ['border-left-style'],
  'border-block': ['border-block-style'],
  'border-inline': ['border-inline-style'],
  'border-style': ['border-style'],
};

/** Rules inside the agent-mode block itself already decide their own look. */
const skip = (sel) => /agent-mode|\.thumb|\.track/.test(sel);

source.walkRules((rule) => {
  if (rule.parent.type === 'atrule' && rule.parent.name === 'keyframes') return;
  const props = new Set();
  rule.walkDecls((d) => {
    if (SIDES[d.prop] && /\bsolid\b/.test(d.value)) for (const p of SIDES[d.prop]) props.add(p);
  });
  if (!props.size) return;
  const selectors = rule.selectors.filter((s) => !skip(s));
  if (!selectors.length) return;
  const copy = postcss.rule({ selectors: selectors.map((s) => `html.agent-mode ${s.replace(/^(html|:root)\b/, '')}`.trim()) });
  for (const p of props) copy.append({ prop: p, value: 'dashed' });
  // Keep @media wrappers so a side is only dashed where the rule applies.
  let target = out;
  if (rule.parent.type === 'atrule') {
    const at = postcss.atRule({ name: rule.parent.name, params: rule.parent.params });
    out.append(at);
    target = at;
  }
  target.append(copy);
});

writeFileSync(`${root}src/agent-mode.generated.css`,
  `/* Generated by scripts/agent-mode-css.mjs from styles.css. Do not edit. */\n${out.toString()}\n`);
console.log(`agent-mode.generated.css: ${out.nodes.length} rules`);
